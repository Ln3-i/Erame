        // 资源/场景/音频能力需要 Addressables：框架包不再声明该依赖，改为生成前检查工程 manifest
        internal static bool HasAddressablesPackage(){
            try{
                var projectRoot = Directory.GetParent(Application.dataPath)?.FullName;
                if (string.IsNullOrEmpty(projectRoot)) return true;
                var manifestPath = projectRoot + "/Packages/manifest.json";
                return File.Exists(manifestPath) && File.ReadAllText(manifestPath).Contains("com.unity.addressables");
            }
            catch (Exception e){
                Debug.LogWarning("[Erame] 读取 Packages/manifest.json 失败：" + e.Message);
                return true; // 读不到就不拦，避免误伤
            }
        }

        /// <summary>按能力集合生成：只写被勾选能力的契约、实现与模块注册，未勾选的服务不会出现在工程里。</summary>
        public static void Generate(IReadOnlyCollection<string> capabilities){
            capabilities = ErameCapabilities.Resolve(capabilities);

            if (ErameCapabilities.RequiresAddressables(capabilities) && !HasAddressablesPackage()){
                Debug.LogWarning("[Erame] 选中的能力依赖 com.unity.addressables，但工程 Packages/manifest.json 里没有该包：" +
                                 "生成的项目将无法编译。请先在 Package Manager 里安装 Addressables。");
            }
            var ns = ToNamespace(Path.GetFileName(GameRoot));
            var scriptsRoot = GameRoot + "/Scripts";
            var modulesRoot = scriptsRoot + "/Modules";
            var runtimeRoot = scriptsRoot + "/Runtime";
            var entryPath = scriptsRoot + "/" + EntryFileName;
            var asmdefPath = scriptsRoot + "/" + AsmdefFileName;
            var runtimeAsmdefPath = runtimeRoot + "/" + ns + ".Runtime.asmdef";
            var groups = ErameCapabilities.SelectedGroups(capabilities);
            var scenePath = GameRoot + "/Scenes/" + SceneFileName;
            var settingsPath = GameRoot + "/Settings/" + SettingsFileName;

            var existing = new List<string>();
            if (File.Exists(entryPath)) existing.Add(entryPath);
            if (File.Exists(asmdefPath)) existing.Add(asmdefPath);
            if (File.Exists(runtimeAsmdefPath)) existing.Add(runtimeAsmdefPath);
            foreach (var group in groups){
                var modulePath = modulesRoot + "/" + group.ClassName + ".cs";
                if (File.Exists(modulePath)) existing.Add(modulePath);
            }
            if (File.Exists(scenePath)) existing.Add(scenePath);

            if (existing.Count > 0){
                var titles = capabilities.Select(id => ErameCapabilities.Find(id)?.Title).Where(t => t != null);
                var confirmed = EditorUtility.DisplayDialog(
                    "Erame 生成项目示例",
                    "目标已存在：\n\n" + string.Join("\n", existing) +
                    $"\n\n本次生成 {capabilities.Count} 项能力：{string.Join("、", titles)}" +
                    "\n\n入口与场景会重新生成（入口里的自定义修改会丢失）；模块只在带 auto-generated 标记时覆盖；已存在的运行时文件不会被覆盖。是否继续？",
                    "生成",
                    "取消");
                if (!confirmed) return;
            }

            EnsureFolder(GameRoot);
            foreach (var folder in EmptyFolders){
                EnsureFolder(GameRoot + "/" + folder);
            }
            EnsureFolder(modulesRoot);
            EnsureFolder(runtimeRoot);

            var entryGuid = WriteTextWithMeta(entryPath, BuildEntryTemplate(ns, groups));

            // 一个能力组一个模块文件：带 auto-generated 标记才覆盖，避免冲掉业务在模块里手写的注册
            var modulesWritten = 0;
            var modulesKept = 0;
            foreach (var group in groups){
                if (WriteModuleFile(modulesRoot + "/" + group.ClassName + ".cs", BuildModuleTemplate(ns, group.Id, capabilities))){
                    modulesWritten++;
                }
                else{
                    modulesKept++;
                }
            }
            if (!File.Exists(asmdefPath)) WriteTextWithMeta(asmdefPath, AsmdefTemplate.Replace("__NS__", ns));
            if (!File.Exists(runtimeAsmdefPath)) WriteTextWithMeta(runtimeAsmdefPath, RuntimeAsmdefTemplate.Replace("__NS__", ns));

            // Runtime 契约与实现属于业务工程：只生成被勾选能力的文件，之后可自由修改或删除
            CopyRuntimeTemplates(runtimeRoot, ns, capabilities);

            WriteKeepFiles();

            AssetDatabase.Refresh();

            // 先创建设置资产，再写场景：入口组件必须直接引用设置资产，
            // 否则运行时只读 ErameSettings.Default（空实例），资产里的密钥/日志级别全部不生效
            var settingsCreated = EnsureSettingsAsset(settingsPath);
            var settingsGuid = AssetDatabase.AssetPathToGUID(settingsPath);
            if (string.IsNullOrEmpty(settingsGuid)){
                Debug.LogWarning("[Erame] 无法获取设置资产 GUID，生成的入口将不引用设置资产，配置不会生效。");
            }

            if (!File.Exists(scenePath + ".meta") || File.Exists(scenePath)){
                WriteTextWithMeta(scenePath, BuildSceneYaml(entryGuid, settingsGuid));
                // 场景是写盘生成的，刷新一次让 Unity 导入，后续才能加载为 SceneAsset
                AssetDatabase.Refresh();
            }

            var sceneAsset = AssetDatabase.LoadAssetAtPath<SceneAsset>(scenePath);
            if (sceneAsset != null){
                Selection.activeObject = sceneAsset;
                EditorGUIUtility.PingObject(sceneAsset);
            }

            Debug.Log(
                $"[Erame] 已生成项目示例：\n" +
                $"  能力（{capabilities.Count}）: " +
                string.Join("、", capabilities.Select(id => ErameCapabilities.Find(id)?.Title).Where(t => t != null)) + "\n" +
                $"  程序集: {asmdefPath}\n" +
                $"          {runtimeAsmdefPath}\n" +
                $"  入口: {entryPath}\n" +
                $"  模块: {modulesRoot}（写入 {modulesWritten} 个" +
                (modulesKept > 0 ? $"，保留 {modulesKept} 个非自动生成的文件" : "") + "）\n" +
                $"  运行时: {runtimeRoot}（契约/实现，可直接修改或删除）\n" +
                $"  设置: {settingsPath}" + (settingsCreated ? "" : "（已存在，未覆盖）") + "\n" +
                $"  场景: {scenePath}\n" +
                "  目录: Art/(Textures,Materials,Models)、Audio、Prefabs、Scripts/(Modules)、Settings");
        }

        // 模块文件是可再生的机械装配：只有带 auto-generated 标记才覆盖。
        // 业务往模块里手写了注册（于是删掉了标记）时保留原文件，并在日志里提示。
        private static bool WriteModuleFile(string assetPath, string content){
            if (File.Exists(assetPath)){
                var existing = File.ReadAllText(assetPath, Encoding.UTF8);
                if (!existing.Contains(GeneratedMarker)){
                    Debug.LogWarning($"[Erame] 模块已存在且不是自动生成的，保留原文件：{assetPath}");
                    return false;
                }
            }

            WriteTextWithMeta(assetPath, content);
            return true;
        }

        // 框架设置是可选资产：已存在时绝不覆盖，避免冲掉用户已固定的存档密钥
        private static bool EnsureSettingsAsset(string assetPath){
            if (File.Exists(assetPath)) return false;

            var instance = ScriptableObject.CreateInstance<ErameSettings>();
            AssetDatabase.CreateAsset(instance, assetPath);

            var serialized = new SerializedObject(instance);
            var keyProperty = serialized.FindProperty("saveKey");
            if (keyProperty != null){
                keyProperty.stringValue = ErameEditorUtility.GenerateSaveKey();
                serialized.ApplyModifiedPropertiesWithoutUndo();
            }

            EditorUtility.SetDirty(instance);
            AssetDatabase.SaveAssets();
            return true;
        }

        // 空目录不会进 Git，写 .gitkeep 占位（Unity 会忽略以 . 开头的文件，无需 meta）
        private static void WriteKeepFiles(){
            foreach (var folder in EmptyFolders){
                var keepPath = GameRoot + "/" + folder + "/" + FolderKeepFileName;
                if (File.Exists(keepPath)) continue;
                File.WriteAllText(keepPath, string.Empty, new UTF8Encoding(false));
            }
        }

        private static void EnsureFolder(string path){
            if (AssetDatabase.IsValidFolder(path)) return;

            var parent = Path.GetDirectoryName(path)?.Replace('\\', '/');
            var name = Path.GetFileName(path);
            if (string.IsNullOrEmpty(parent) || string.IsNullOrEmpty(name)) return;

            EnsureFolder(parent);
            AssetDatabase.CreateFolder(parent, name);
        }

        /// <summary>
        /// 把包内 Samples~/Runtime 的契约与实现生成为业务工程代码，且只生成被勾选能力的文件。
        /// 生成之后这些文件归业务所有：可以直接修改实现，也可以删掉并在模块里换成自己的实现。
        /// </summary>
        private static void CopyRuntimeTemplates(string runtimeRoot, string ns, IReadOnlyCollection<string> capabilities){
            var packagePath = FindFrameworkPackagePath();
            if (string.IsNullOrEmpty(packagePath)){
                Debug.LogWarning("[Erame] 未找到 com.erame.framework 包路径，Runtime 契约/实现未生成。");
                return;
            }

            var templateRoot = Path.Combine(packagePath, "Samples~", "Runtime");
            if (!Directory.Exists(templateRoot)){
                Debug.LogWarning($"[Erame] 未找到 Runtime 模板目录: {templateRoot}");
                return;
            }

            var copied = 0;
            var skipped = 0;

            foreach (var file in Directory.GetFiles(templateRoot, "*.cs", SearchOption.AllDirectories)){
                var relative = file.Substring(templateRoot.Length)
                    .TrimStart(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar)
                    .Replace('\\', '/');

                if (!ErameCapabilities.Includes(capabilities, relative)) continue;

                var target = Path.Combine(runtimeRoot, relative).Replace('\\', '/');

                // 契约与实现一旦生成就归业务所有：已存在时保留，避免覆盖开发者对存档等文件的修改。
                // 但允许"补生成"：新增能力时只补缺的文件，不重写已有文件。
                if (File.Exists(target)){
                    skipped++;
                    continue;
                }

                EnsureFolder(Path.GetDirectoryName(target).Replace('\\', '/'));
                WriteTextWithMeta(target, File.ReadAllText(file, Encoding.UTF8).Replace("__NS__", ns));
                copied++;
            }

            Debug.Log($"[Erame] 生成运行时文件 {copied} 个" +
                      (skipped > 0 ? $"，跳过已存在 {skipped} 个（保留业务修改）" : "") + "。");
        }

        private static string FindFrameworkPackagePath(){
            var info = UnityEditor.PackageManager.PackageInfo.GetAllRegisteredPackages()
                .FirstOrDefault(p => p.name == ErameEditorUtility.FrameworkPackageName);
            return info?.resolvedPath;
        }

        private static string WriteTextWithMeta(string assetPath, string content){
            var guid = Guid.NewGuid().ToString("N");
            File.WriteAllText(assetPath, content, new UTF8Encoding(false));

            string importer;
            if (assetPath.EndsWith(".cs")){
                importer = "MonoImporter:\n" +
                           "  externalObjects: {}\n" +
                           "  serializedVersion: 2\n" +
                           "  defaultReferences: []\n" +
                           "  executionOrder: 0\n" +
                           "  icon: {instanceID: 0}\n" +
                           "  userData: \n" +
                           "  assetBundleName: \n" +
                           "  assetBundleVariant: \n";
            }
            else if (assetPath.EndsWith(".asmdef")){
                importer = "AssemblyDefinitionImporter:\n" +
                           "  externalObjects: {}\n" +
                           "  userData: \n" +
                           "  assetBundleName: \n" +
                           "  assetBundleVariant: \n";
            }
            else{
                importer = "DefaultImporter:\n" +
                           "  externalObjects: {}\n" +
                           "  userData: \n" +
                           "  assetBundleName: \n" +
                           "  assetBundleVariant: \n";
            }

            File.WriteAllText(assetPath + ".meta",
                $"fileFormatVersion: 2\nguid: {guid}\n{importer}", new UTF8Encoding(false));
            return guid;
        }

