        // 入口按实际生成的模块拼接：删能力 = 删模块文件 + 删这里一行
        private static string BuildEntryTemplate(string ns, IReadOnlyList<ErameCapabilityGroup> groups){
            var sb = new StringBuilder(512);
            sb.Append("using Erame.Core;\n");
            sb.Append("using Erame.Runtime.Bootstrap;\n");
            sb.Append("using __NS__.Scripts.Modules;\n\n");
            sb.Append("namespace __NS__{\n");
            sb.Append("    /// <summary>\n");
            sb.Append("    /// 项目入口：把本组件挂到场景对象上即可启动整个项目。\n");
            sb.Append("    /// 模块按能力域拆分，不需要的领域删掉对应 *Module.cs 和下面一行 AddModule 即可。\n");
            sb.Append("    /// </summary>\n");
            sb.Append("    public sealed class GameEntry : ErameMonoEntry{\n");
            sb.Append("        public override void Configure(ErameBuilder builder){\n");

            if (groups.Count == 0){
                sb.Append("            // 本次没有生成任何模块。\n");
            }
            else{
                sb.Append("            builder");
                for (var i = 0; i < groups.Count; i++){
                    sb.Append(i == 0 ? "\n                ." : "\n                .");
                    sb.Append("AddModule<").Append(groups[i].ClassName).Append(">()");
                }
                sb.Append(";\n");
            }

            sb.Append("        }\n    }\n}\n");
            return sb.ToString().Replace("__NS__", ns);
        }

        // 模块只写本组被勾选能力的注册行：一个模块一个文件，删能力就是删文件
        private static string BuildModuleTemplate(string ns, string group, IReadOnlyCollection<string> capabilities){
            var info = ErameCapabilities.FindGroup(group);
            var className = info?.ClassName ?? (group + "Module");
            var summary = info?.Summary ?? "按需生成的模块。";

            var sb = new StringBuilder(1024);
            sb.Append(GeneratedMarker).Append('\n');
            sb.Append("using Erame.Core;\n");
            sb.Append("using Erame.Runtime.Config;\n");
            sb.Append("using __NS__.Runtime;\n");
            sb.Append("using __NS__.Runtime.Services;\n\n");
            sb.Append("namespace __NS__.Scripts.Modules{\n");
            sb.Append("    /// <summary>").Append(summary).Append("</summary>\n");
            sb.Append("    public sealed class ").Append(className).Append(" : IModule{\n");
            sb.Append("        public void Configure(IServiceRegistrar registrar){\n");

            if (ErameCapabilities.NeedsSettings(capabilities, group)){
                sb.Append("            var settings = ErameSettings.Default;\n\n");
            }

            var any = false;
            foreach (var capability in ErameCapabilities.All){
                if (capability.Group != group || !capabilities.Contains(capability.Id)) continue;

                any = true;
                sb.Append("            // ").Append(capability.Title).Append('\n');
                foreach (var registration in capability.Registrations){
                    sb.Append("            ").Append(registration).Append('\n');
                }
                sb.Append('\n');
            }

            if (!any){
                sb.Append("            // 本次没有选择本模块的能力：需要时再运行「Erame/示例/生成项目（按需）」。\n");
            }

            sb.Append("        }\n    }\n}\n");
            return sb.ToString().Replace("__NS__", ns);
        }


